#!/usr/bin/env node
// 정책 문서 원본 → 앱 코드 생성 — 법률 카드 t_eb7f13e9
// docs/legal/*(내변호사 소유, 커밋 b50fd9ff)가 Single Source of Truth.
// 앱에 번들되는 src/lib/legalDocs.generated.ts는 **이 스크립트로만** 재생성한다 (수동 편집 금지 —
// 원본과 사본이 어긋나면 법무 검증이 무너진다). ?raw 임포트는 Metro에서 보장되지 않아(webpack 유산
// 통념 — RNWeb/Metro 차이) 코드 생성 방식을 택함: tsc·unit test·웹 export 전부에서 동작.
// 실행: node scripts/sync-legal-docs.cjs   (원본 변경 시마다 커밋 전 필수)
const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..', '..', '..', '..'); // apps/mobile/MyAgentTalk/scripts → repo root
const SRC = path.join(REPO, 'docs', 'legal');
const OUT = path.join(__dirname, '..', 'src', 'lib', 'legalDocs.generated.ts');
const MAP = {
  'terms-of-service-ko.md': ['terms', 'ko'],
  'terms-of-service-en.md': ['terms', 'en'],
  'privacy-policy-ko.md': ['privacy', 'ko'],
  'privacy-policy-en.md': ['privacy', 'en'],
};

const docs = {};
let missing = 0;
for (const [from, [kind, locale]] of Object.entries(MAP)) {
  const src = path.join(SRC, from);
  if (!fs.existsSync(src)) { console.error(`MISSING 원본: ${src}`); missing++; continue; }
  (docs[kind] ??= {})[locale] = fs.readFileSync(src, 'utf8');
}
if (missing) { console.error(`원본 누락 ${missing}건 — 생성 중단`); process.exit(1); }

const body = JSON.stringify(docs, null, 2).replace(/</g, '\\u003c'); // </script> 류 인젝 방어
const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ');
const file = `// Generated by scripts/sync-legal-docs.cjs — DO NOT EDIT.\n` +
  `// 원본: docs/legal/{terms-of-service,privacy-policy}-{ko,en}.md (내변호사 소유).\n` +
  `// 동기화: ${stamp} UTC\n` +
  `export const legalDocsGenerated = ${body} as const;\n`;

const before = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
// 타임스탬프 행을 제외한 본문이 동일하면 재작성 안 함 (불요 diff 방지)
if (before && before.replace(/^\/\/ 동기화: .*\n/m, '') === file.replace(/^\/\/ 동기화: .*\n/m, '')) {
  console.log('legalDocs.generated.ts already in sync');
} else {
  fs.writeFileSync(OUT, file);
  console.log('GENERATED src/lib/legalDocs.generated.ts');
}
// 웹 호스팅 대비 사본-assets도 동일 원본으로 유지 (Netlify public/legal 등 2차 배치 시 사용)
const ASSETS = path.join(__dirname, '..', 'assets', 'legal');
fs.mkdirSync(ASSETS, { recursive: true });
for (const [from, [kind, locale]] of Object.entries(MAP)) {
  fs.writeFileSync(path.join(ASSETS, `${kind}-${locale}.md`), fs.readFileSync(path.join(SRC, from)));
}
console.log('정책 문서 동기화 완료');
